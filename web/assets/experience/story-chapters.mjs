export function journeyDetails(session,pack){
 const labels=session.trail.map(s=>pack.nodes[s.node].choices.find(c=>c.id===s.choiceId)?.label).filter(Boolean);
 const extended=session.trail.some(s=>s.choiceId==='long'&&s.node==='start');
 if(!extended)return {extended:false,chapter:pack.nodes[session.node].chapter||'短篇散步',outcomes:[],labels};
 const selected=id=>session.trail.some(s=>s.choiceId===id&&s.node.startsWith('long-'));
 const outcomes=[];
 if(selected('take'))outcomes.push('剧情小物已收好');else if(selected('wish'))outcomes.push('愿望留到下次');
 if(selected('rich'))outcomes.push('浓巧克力');else if(selected('fresh')||selected('replace'))outcomes.push('水果塔');else if(selected('wait'))outcomes.push('留白与热茶');
 if(selected('indoors'))outcomes.push('雨夜窗边');else if(selected('outside'))outcomes.push('灯下夜归');
 return {extended:true,chapter:pack.nodes[session.node].chapter||'尾声 · 手记',outcomes,labels};
}
